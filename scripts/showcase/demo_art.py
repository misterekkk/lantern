"""The website demo's result pictures, drawn by the showcase's own functions (drawings.py), as site/public/demo/art.js.

    python3 scripts/showcase/demo_art.py
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from drawings import beach, clip_rect, park, pitch  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "site" / "public" / "demo" / "art.js"


def svg(name: str, w: int, h: int, body: str) -> str:
    return (f'<svg viewBox="0 0 {w} {h}" preserveAspectRatio="xMidYMid slice"><defs>{clip_rect("c" + name, 0, 0, w, h, 0)}'
            f"</defs>{body}</svg>")


art = {
    "beachDog": svg("bd", 160, 120, beach(0, 0, 160, 120, "cbd", 0)),
    "sunset": svg("ss", 160, 120, beach(0, 0, 160, 120, "css", 1)),
    "parkDog": svg("pd", 160, 120, park(0, 0, 160, 120, "cpd")),
    "vlog": svg("vl", 320, 200, pitch(0, 0, 320, 200, "cvl")),
}
OUT.write_text("// Generated by scripts/showcase/demo_art.py from the showcase's drawings: do not edit.\n"
               f"window.SHOWCASE_ART = {json.dumps(art, ensure_ascii=False, indent=1)};\n")
print(OUT)
