import AppKit
import LanternCore

/// Clipboard history, like Spotlight's: off unless chosen in Settings → Privacy. Copied text is kept in this app's
/// memory only (never written to disk or to the index), for 30 minutes or 8 hours, and forgotten when Lantern quits.
/// Items that apps mark as private (password managers: the nspasteboard.org concealed / transient types) are skipped.
@MainActor
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let key = "clipboardHistory"  // off | 30m | 8h

    struct Item {
        let id = UUID()
        let text: String
        let date: Date
        let app: String?
    }

    private(set) var items: [Item] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private static let maxItems = 200
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ]

    var retention: TimeInterval? {
        switch UserDefaults.standard.string(forKey: Self.key) {
        case "30m": 30 * 60
        case "8h": 8 * 3600
        default: nil
        }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            Task { @MainActor in ClipboardHistory.shared.poll() }
        }
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard let keep = retention else {
            items = []
            return
        }
        prune(keep)
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes),
              let text = board.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty, text.count <= 20_000
        else { return }
        items.removeAll { $0.text == text }
        items.insert(Item(text: text, date: Date(), app: NSWorkspace.shared.frontmostApplication?.localizedName), at: 0)
        if items.count > Self.maxItems { items.removeLast(items.count - Self.maxItems) }
    }

    private func prune(_ keep: TimeInterval) {
        items.removeAll { Date().timeIntervalSince($0.date) > keep }
    }

    func clear() { items = [] }

    /// Items containing the query (compared folded); an empty query lists the most recent ones.
    func matches(_ query: String, limit: Int) -> [Item] {
        guard let keep = retention else { return [] }
        prune(keep)
        let q = TextFold.fold(query.trimmingCharacters(in: .whitespaces))
        let found = q.isEmpty ? items : items.filter { TextFold.fold($0.text).contains(q) }
        return Array(found.prefix(limit))
    }

    /// ↩ on an item: back on the clipboard.
    func copy(_ path: String) {
        guard let item = items.first(where: { "clipboard:\($0.id)" == path }) else { return }
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(item.text, forType: .string)
    }

    func section(for query: String, limit: Int) -> ResultSection? {
        let found = matches(query, limit: limit)
        guard !found.isEmpty else { return nil }
        let ago = RelativeDateTimeFormatter()
        ago.unitsStyle = .full
        let rows = found.map { item -> SearchResult in
            let lines = item.text.split(whereSeparator: \.isNewline)
            let when = ago.localizedString(for: item.date, relativeTo: Date())
            let detail = [String(localized: "Clipboard"), when, item.app].compactMap { $0 }.joined(separator: " · ")
            var row = SearchResult(path: "clipboard:\(item.id)", chunkId: 0, symbol: String(lines.first ?? ""),
                                   preview: detail, kind: "clipboard")
            row.settingSymbol = "doc.on.clipboard"
            row.settingColor = "Gray"
            return row
        }
        return ResultSection(kind: .clipboard, results: rows)
    }
}
